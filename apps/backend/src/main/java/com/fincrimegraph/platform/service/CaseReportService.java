package com.fincrimegraph.platform.service;

import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDDocumentInformation;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDFont;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Objects;

@Service
public class CaseReportService {

    public byte[] render(
            CaseWorkspaceService.CaseWorkspaceView workspace,
            String generatedBy
    ) {
        Objects.requireNonNull(
                workspace,
                "workspace"
        );

        String actor =
                normalize(
                        generatedBy,
                        "unknown"
                );

        Instant generatedAt =
                Instant.now();

        try (
                PDDocument document =
                        new PDDocument();

                ByteArrayOutputStream output =
                        new ByteArrayOutputStream()
        ) {
            configureMetadata(
                    document,
                    workspace,
                    actor
            );

            try (
                    ReportWriter writer =
                            new ReportWriter(
                                    document
                            )
            ) {
                renderHeader(
                        writer,
                        workspace,
                        actor,
                        generatedAt
                );

                renderPrimaryAlert(
                        writer,
                        workspace
                                .primaryAlert()
                );

                renderEvidence(
                        writer,
                        workspace
                                .evidence()
                );

                renderNotes(
                        writer,
                        workspace
                                .notes()
                );

                renderTimeline(
                        writer,
                        workspace
                                .timeline()
                );

                renderResolution(
                        writer,
                        workspace
                );

                writer.section(
                        "Report control"
                );

                writer.field(
                        "Generated by",
                        actor
                );

                writer.field(
                        "Generated at",
                        generatedAt.toString()
                );

                writer.field(
                        "Report source",
                        "FinCrime Graph investigation workspace"
                );

                writer.paragraph(
                        "Evidence fingerprints in this report are SHA-256 "
                                + "digests of the preserved evidence reference "
                                + "and snapshot content."
                );
            }

            document.save(
                    output
            );

            return output
                    .toByteArray();

        } catch (IOException exception) {
            throw new IllegalStateException(
                    "Unable to generate investigation PDF report.",
                    exception
            );
        }
    }

    private void configureMetadata(
            PDDocument document,
            CaseWorkspaceService.CaseWorkspaceView workspace,
            String generatedBy
    ) {
        PDDocumentInformation information =
                document
                        .getDocumentInformation();

        information.setTitle(
                "FinCrime Graph Investigation Report - "
                        + workspace.caseNumber()
        );

        information.setAuthor(
                generatedBy
        );

        information.setSubject(
                "Financial crime investigation case "
                        + workspace.caseNumber()
        );

        information.setCreator(
                "FinCrime Graph"
        );

        information.setProducer(
                "FinCrime Graph / Apache PDFBox"
        );
    }

    private void renderHeader(
            ReportWriter writer,
            CaseWorkspaceService.CaseWorkspaceView workspace,
            String generatedBy,
            Instant generatedAt
    ) throws IOException {

        writer.title(
                "FinCrime Graph Investigation Report"
        );

        writer.subtitle(
                workspace.caseNumber()
                        + " | "
                        + workspace.title()
        );

        writer.spacer(
                6
        );

        writer.field(
                "Status",
                workspace.status()
        );

        writer.field(
                "Priority",
                workspace.priority()
        );

        writer.field(
                "Assigned to",
                workspace.assignedTo()
        );

        writer.field(
                "Created",
                instant(
                        workspace.createdAt()
                )
        );

        writer.field(
                "Updated",
                instant(
                        workspace.updatedAt()
                )
        );

        writer.field(
                "Generated by",
                generatedBy
        );

        writer.field(
                "Generated at",
                generatedAt.toString()
        );

        writer.spacer(
                5
        );

        writer.section(
                "Investigation summary"
        );

        writer.paragraph(
                workspace.summary()
        );
    }

    private void renderPrimaryAlert(
            ReportWriter writer,
            CaseWorkspaceService.PrimaryAlertView alert
    ) throws IOException {

        writer.section(
                "Primary AML alert"
        );

        writer.field(
                "Alert code",
                alert.code()
        );

        writer.field(
                "Alert type",
                alert.type()
        );

        writer.field(
                "Severity",
                alert.severity()
        );

        writer.field(
                "Risk score",
                Integer.toString(
                        alert.riskScore()
                )
        );

        writer.field(
                "Alert status",
                alert.status()
        );

        writer.field(
                "Account",
                alert.accountNumber()
        );

        writer.field(
                "Transaction",
                alert.transactionReference()
        );

        writer.paragraph(
                alert.title()
        );
    }

    private void renderEvidence(
            ReportWriter writer,
            List<
                    CaseWorkspaceService.EvidenceView
                    > evidence
    ) throws IOException {

        writer.section(
                "Preserved evidence"
        );

        if (
                evidence == null
                        || evidence.isEmpty()
        ) {
            writer.paragraph(
                    "No preserved evidence."
            );

            return;
        }

        int index =
                1;

        for (
                CaseWorkspaceService.EvidenceView item
                        : evidence
        ) {
            writer.subheading(
                    "Evidence "
                            + index
                            + " - "
                            + item.title()
            );

            writer.field(
                    "Type",
                    item.evidenceType()
            );

            writer.field(
                    "Reference",
                    normalize(
                            item.referenceType(),
                            "UNKNOWN"
                    )
                            + ":"
                            + normalize(
                            item.referenceId(),
                            "UNKNOWN"
                    )
            );

            writer.field(
                    "Captured",
                    instant(
                            item.createdAt()
                    )
            );

            writer.field(
                    "SHA-256",
                    evidenceFingerprint(
                            item
                    )
            );

            writer.paragraph(
                    item.description()
            );

            writer.monospace(
                    item.snapshotText()
            );

            writer.spacer(
                    5
            );

            index++;
        }
    }

    private void renderNotes(
            ReportWriter writer,
            List<
                    CaseWorkspaceService.NoteView
                    > notes
    ) throws IOException {

        writer.section(
                "Analyst notes"
        );

        if (
                notes == null
                        || notes.isEmpty()
        ) {
            writer.paragraph(
                    "No analyst notes."
            );

            return;
        }

        for (
                CaseWorkspaceService.NoteView note
                        : notes
        ) {
            writer.subheading(
                    normalize(
                            note.authorName(),
                            "Unknown analyst"
                    )
                            + " | "
                            + instant(
                            note.createdAt()
                    )
            );

            writer.paragraph(
                    note.body()
            );

            writer.spacer(
                    4
            );
        }
    }

    private void renderTimeline(
            ReportWriter writer,
            List<
                    CaseWorkspaceService.EventView
                    > timeline
    ) throws IOException {

        writer.section(
                "Investigation activity timeline"
        );

        if (
                timeline == null
                        || timeline.isEmpty()
        ) {
            writer.paragraph(
                    "No investigation activity."
            );

            return;
        }

        for (
                CaseWorkspaceService.EventView event
                        : timeline
        ) {
            writer.bullet(
                    instant(
                            event.createdAt()
                    )
                            + " | "
                            + normalize(
                            event.eventType(),
                            "EVENT"
                    )
                            + " | "
                            + normalize(
                            event.actorName(),
                            "Unknown actor"
                    )
            );

            writer.paragraph(
                    event.description()
            );
        }
    }

    private void renderResolution(
            ReportWriter writer,
            CaseWorkspaceService.CaseWorkspaceView workspace
    ) throws IOException {

        writer.section(
                "Case disposition"
        );

        writer.field(
                "Disposition",
                workspace.disposition()
        );

        writer.field(
                "Closed at",
                instant(
                        workspace.closedAt()
                )
        );

        if (
                workspace.resolutionSummary()
                        == null
                        || workspace
                        .resolutionSummary()
                        .isBlank()
        ) {
            writer.paragraph(
                    "No final resolution summary has been recorded."
            );

            return;
        }

        writer.paragraph(
                workspace
                        .resolutionSummary()
        );
    }

    String evidenceFingerprint(
            CaseWorkspaceService.EvidenceView evidence
    ) {
        String input =
                normalize(
                        evidence.referenceType(),
                        ""
                )
                        + "|"
                        + normalize(
                        evidence.referenceId(),
                        ""
                )
                        + "|"
                        + normalize(
                        evidence.snapshotText(),
                        ""
                );

        try {
            MessageDigest digest =
                    MessageDigest.getInstance(
                            "SHA-256"
                    );

            return HexFormat
                    .of()
                    .formatHex(
                            digest.digest(
                                    input.getBytes(
                                            StandardCharsets.UTF_8
                                    )
                            )
                    );

        } catch (
                NoSuchAlgorithmException exception
        ) {
            throw new IllegalStateException(
                    "SHA-256 is unavailable.",
                    exception
            );
        }
    }

    private String instant(
            Instant value
    ) {
        return value == null
                ? "Not recorded"
                : value.toString();
    }

    private String normalize(
            String value,
            String fallback
    ) {
        return value == null
                || value.isBlank()
                ? fallback
                : value.trim();
    }

    private static final class ReportWriter
            implements AutoCloseable {

        private static final float MARGIN =
                48f;

        private static final float BOTTOM_MARGIN =
                48f;

        private static final float CONTENT_WIDTH =
                PDRectangle.A4.getWidth()
                        - (2 * MARGIN);

        private final PDDocument document;

        private final PDFont regular =
                new PDType1Font(
                        Standard14Fonts
                                .FontName
                                .HELVETICA
                );

        private final PDFont bold =
                new PDType1Font(
                        Standard14Fonts
                                .FontName
                                .HELVETICA_BOLD
                );

        private final PDFont monospace =
                new PDType1Font(
                        Standard14Fonts
                                .FontName
                                .COURIER
                );

        private PDPage page;
        private PDPageContentStream content;
        private float y;

        private ReportWriter(
                PDDocument document
        ) throws IOException {
            this.document =
                    document;

            newPage();
        }

        void title(
                String value
        ) throws IOException {
            writeWrapped(
                    value,
                    bold,
                    18f,
                    23f,
                    0f
            );
        }

        void subtitle(
                String value
        ) throws IOException {
            writeWrapped(
                    value,
                    regular,
                    10f,
                    14f,
                    0f
            );
        }

        void section(
                String value
        ) throws IOException {
            spacer(
                    7f
            );

            ensureSpace(
                    28f
            );

            writeWrapped(
                    value,
                    bold,
                    12f,
                    16f,
                    0f
            );

            spacer(
                    2f
            );
        }

        void subheading(
                String value
        ) throws IOException {
            ensureSpace(
                    24f
            );

            writeWrapped(
                    value,
                    bold,
                    9f,
                    13f,
                    0f
            );
        }

        void field(
                String label,
                String value
        ) throws IOException {
            writeWrapped(
                    normalizeStatic(
                            label,
                            "Field"
                    )
                            + ": "
                            + normalizeStatic(
                            value,
                            "Not recorded"
                    ),
                    regular,
                    8.5f,
                    12f,
                    0f
            );
        }

        void paragraph(
                String value
        ) throws IOException {
            writeWrapped(
                    normalizeStatic(
                            value,
                            "Not recorded"
                    ),
                    regular,
                    8.5f,
                    12f,
                    0f
            );

            spacer(
                    3f
            );
        }

        void bullet(
                String value
        ) throws IOException {
            writeWrapped(
                    "- "
                            + normalizeStatic(
                            value,
                            ""
                    ),
                    regular,
                    8f,
                    11.5f,
                    8f
            );
        }

        void monospace(
                String value
        ) throws IOException {
            writeWrapped(
                    normalizeStatic(
                            value,
                            "No snapshot"
                    ),
                    monospace,
                    6.8f,
                    9.5f,
                    8f
            );
        }

        void spacer(
                float height
        ) throws IOException {
            ensureSpace(
                    height
            );

            y -= height;
        }

        private void writeWrapped(
                String value,
                PDFont font,
                float fontSize,
                float lineHeight,
                float indent
        ) throws IOException {

            List<String> lines =
                    wrap(
                            value,
                            font,
                            fontSize,
                            CONTENT_WIDTH
                                    - indent
                    );

            for (
                    String line
                            : lines
            ) {
                ensureSpace(
                        lineHeight
                );

                writeLine(
                        line,
                        font,
                        fontSize,
                        indent
                );

                y -= lineHeight;
            }
        }

        private void writeLine(
                String value,
                PDFont font,
                float fontSize,
                float indent
        ) throws IOException {

            content.beginText();

            content.setFont(
                    font,
                    fontSize
            );

            content.newLineAtOffset(
                    MARGIN + indent,
                    y
            );

            content.showText(
                    ascii(
                            value
                    )
            );

            content.endText();
        }

        private List<String> wrap(
                String original,
                PDFont font,
                float fontSize,
                float width
        ) throws IOException {

            String value =
                    ascii(
                            normalizeStatic(
                                    original,
                                    ""
                            )
                    );

            if (value.isBlank()) {
                return List.of(
                        ""
                );
            }

            List<String> result =
                    new ArrayList<>();

            for (
                    String paragraph
                            : value.split(
                            "\\R",
                            -1
                    )
            ) {
                if (paragraph.isBlank()) {
                    result.add(
                            ""
                    );

                    continue;
                }

                StringBuilder current =
                        new StringBuilder();

                for (
                        String word
                                : paragraph
                                .trim()
                                .split(
                                        "\\s+"
                                )
                ) {
                    if (
                            textWidth(
                                    word,
                                    font,
                                    fontSize
                            )
                                    > width
                    ) {
                        if (
                                !current.isEmpty()
                        ) {
                            result.add(
                                    current.toString()
                            );

                            current.setLength(
                                    0
                            );
                        }

                        result.addAll(
                                splitLongWord(
                                        word,
                                        font,
                                        fontSize,
                                        width
                                )
                        );

                        continue;
                    }

                    String candidate =
                            current.isEmpty()
                                    ? word
                                    : current
                                    + " "
                                    + word;

                    if (
                            textWidth(
                                    candidate,
                                    font,
                                    fontSize
                            )
                                    <= width
                    ) {
                        if (
                                !current.isEmpty()
                        ) {
                            current.append(
                                    ' '
                            );
                        }

                        current.append(
                                word
                        );

                    } else {
                        result.add(
                                current.toString()
                        );

                        current.setLength(
                                0
                        );

                        current.append(
                                word
                        );
                    }
                }

                if (
                        !current.isEmpty()
                ) {
                    result.add(
                            current.toString()
                    );
                }
            }

            return result;
        }

        private List<String> splitLongWord(
                String word,
                PDFont font,
                float fontSize,
                float width
        ) throws IOException {

            List<String> chunks =
                    new ArrayList<>();

            StringBuilder current =
                    new StringBuilder();

            for (
                    char character
                            : word.toCharArray()
            ) {
                String candidate =
                        current.toString()
                                + character;

                if (
                        !current.isEmpty()
                                && textWidth(
                                candidate,
                                font,
                                fontSize
                        ) > width
                ) {
                    chunks.add(
                            current.toString()
                    );

                    current.setLength(
                            0
                    );
                }

                current.append(
                        character
                );
            }

            if (
                    !current.isEmpty()
            ) {
                chunks.add(
                        current.toString()
                );
            }

            return chunks;
        }

        private float textWidth(
                String value,
                PDFont font,
                float fontSize
        ) throws IOException {
            return font
                    .getStringWidth(
                            ascii(
                                    value
                            )
                    )
                    / 1000f
                    * fontSize;
        }

        private void ensureSpace(
                float required
        ) throws IOException {
            if (
                    y - required
                            >= BOTTOM_MARGIN
            ) {
                return;
            }

            newPage();
        }

        private void newPage()
                throws IOException {

            closeContent();

            page =
                    new PDPage(
                            PDRectangle.A4
                    );

            document.addPage(
                    page
            );

            content =
                    new PDPageContentStream(
                            document,
                            page
                    );

            y =
                    page
                            .getMediaBox()
                            .getHeight()
                            - MARGIN;

            writeLine(
                    "FINCRIME GRAPH | INVESTIGATION REPORT",
                    bold,
                    6.5f,
                    0f
            );

            y -= 16f;
        }

        private void closeContent()
                throws IOException {
            if (
                    content != null
            ) {
                content.close();

                content = null;
            }
        }

        @Override
        public void close()
                throws IOException {
            closeContent();
        }

        private static String normalizeStatic(
                String value,
                String fallback
        ) {
            return value == null
                    || value.isBlank()
                    ? fallback
                    : value.trim();
        }

        private static String ascii(
                String value
        ) {
            String normalized =
                    value
                            .replace(
                                    '\u2018',
                                    '\''
                            )
                            .replace(
                                    '\u2019',
                                    '\''
                            )
                            .replace(
                                    '\u201C',
                                    '"'
                            )
                            .replace(
                                    '\u201D',
                                    '"'
                            )
                            .replace(
                                    '\u2013',
                                    '-'
                            )
                            .replace(
                                    '\u2014',
                                    '-'
                            );

            StringBuilder output =
                    new StringBuilder(
                            normalized.length()
                    );

            for (
                    char character
                            : normalized
                            .toCharArray()
            ) {
                if (
                        character == '\n'
                                || character == '\r'
                                || (
                                character >= 32
                                        && character <= 126
                        )
                ) {
                    output.append(
                            character
                    );

                } else {
                    output.append(
                            '?'
                    );
                }
            }

            return output.toString();
        }
    }
}
