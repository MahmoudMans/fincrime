import type { CustomerRiskAssessment } from "@/lib/api";
import type { CsvColumn } from "@/lib/csv";
import { countBy, matchesQuery } from "@/lib/list-utils";

export const RISK_BANDS = [
  "CRITICAL",
  "HIGH",
  "MEDIUM",
  "LOW",
] as const;

export type RiskSort = "score-desc" | "score-asc" | "name" | "country";

export interface RiskFilters {
  q: string;
  /** "ALL" or a risk band. */
  band: string;
  /** "ALL" or a country code. */
  country: string;
  /** "ALL" or a customer profile tier. */
  tier: string;
  sort: RiskSort;
}

export const DEFAULT_RISK_FILTERS: RiskFilters = {
  q: "",
  band: "ALL",
  country: "ALL",
  tier: "ALL",
  sort: "score-desc",
};

export const RISK_SORTS: ReadonlyArray<{
  value: RiskSort;
  label: string;
}> = [
  { value: "score-desc", label: "Highest score first" },
  { value: "score-asc", label: "Lowest score first" },
  { value: "name", label: "Customer name A to Z" },
  { value: "country", label: "Country, then score" },
];

const SORT_VALUES: readonly string[] = RISK_SORTS.map(
  (option) => option.value
);

function text(value: unknown, fallback: string) {
  return typeof value === "string" ? value : fallback;
}

/** Saved views come from storage, so their shape is not trusted. */
export function normalizeRiskFilters(value: unknown): RiskFilters {
  if (typeof value !== "object" || value === null) {
    return DEFAULT_RISK_FILTERS;
  }

  const raw = value as Record<string, unknown>;

  const sort = text(raw.sort, "score-desc");

  return {
    q: text(raw.q, ""),
    band: text(raw.band, "ALL"),
    country: text(raw.country, "ALL"),
    tier: text(raw.tier, "ALL"),
    sort: SORT_VALUES.includes(sort)
      ? (sort as RiskSort)
      : "score-desc",
  };
}

export function isDefaultRiskFilters(filters: RiskFilters) {
  return (
    filters.q.trim() === "" &&
    filters.band === "ALL" &&
    filters.country === "ALL" &&
    filters.tier === "ALL" &&
    filters.sort === "score-desc"
  );
}

export function filterRisk(
  items: readonly CustomerRiskAssessment[],
  filters: RiskFilters
): CustomerRiskAssessment[] {
  return items.filter((item) => {
    if (filters.band !== "ALL" && item.riskBand !== filters.band) {
      return false;
    }

    if (
      filters.country !== "ALL" &&
      item.countryCode !== filters.country
    ) {
      return false;
    }

    if (
      filters.tier !== "ALL" &&
      item.customerRiskTier !== filters.tier
    ) {
      return false;
    }

    return matchesQuery(filters.q, [
      item.customerName,
      item.countryCode,
      item.customerRiskTier,
      item.riskBand,
      item.customerId,
      item.modelVersion,
    ]);
  });
}

/** Counts for one filter group, given every other active filter. */
export function riskFacetCounts(
  items: readonly CustomerRiskAssessment[],
  filters: RiskFilters,
  facet: "band" | "country" | "tier"
): Record<string, number> {
  const rows = filterRisk(items, { ...filters, [facet]: "ALL" });

  const counts = countBy(rows, (item) => {
    switch (facet) {
      case "band":
        return item.riskBand;
      case "country":
        return item.countryCode;
      default:
        return item.customerRiskTier;
    }
  });

  counts.ALL = rows.length;

  return counts;
}

/** Returns a new sorted array. */
export function sortRisk(
  items: readonly CustomerRiskAssessment[],
  sort: RiskSort
): CustomerRiskAssessment[] {
  const byScore = (
    a: CustomerRiskAssessment,
    b: CustomerRiskAssessment
  ) => b.score - a.score || a.customerName.localeCompare(b.customerName);

  return [...items].sort((a, b) => {
    switch (sort) {
      case "score-asc":
        return a.score - b.score || a.customerName.localeCompare(b.customerName);

      case "name":
        return (
          a.customerName.localeCompare(b.customerName) ||
          byScore(a, b)
        );

      case "country":
        return a.countryCode.localeCompare(b.countryCode) || byScore(a, b);

      default:
        return byScore(a, b);
    }
  });
}

export const RISK_CSV_COLUMNS: CsvColumn<CustomerRiskAssessment>[] = [
  { header: "Customer", value: (item) => item.customerName },
  { header: "Customer ID", value: (item) => item.customerId },
  { header: "Country", value: (item) => item.countryCode },
  { header: "Profile tier", value: (item) => item.customerRiskTier },
  { header: "Risk band", value: (item) => item.riskBand },
  { header: "Score", value: (item) => item.score },
  { header: "Model version", value: (item) => item.modelVersion },
  { header: "Generated by", value: (item) => item.generatedBy },
  { header: "Generated at (UTC)", value: (item) => item.generatedAt },
  { header: "Assessment ID", value: (item) => item.id },
  { header: "Batch ID", value: (item) => item.batchId },
];

/** Latest generation time among the assessments, or null. */
export function latestGenerated(
  items: readonly CustomerRiskAssessment[]
): string | null {
  let latest: string | null = null;

  for (const item of items) {
    if (latest === null || item.generatedAt > latest) {
      latest = item.generatedAt;
    }
  }

  return latest;
}
